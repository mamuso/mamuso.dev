#!/usr/bin/env python3
"""Manual only: python scripts/subset-fonts.py [--drop-hinting]. See docs/fonts.md."""
import argparse
import hashlib
import html
import json
import tempfile
from pathlib import Path
from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.pens.recordingPen import DecomposingRecordingPen

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'app/fonts/courier-prime'
DEST = ROOT / 'public/fonts'
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--drop-hinting', action='store_true', help='Opt-in visual regression on hinting renderers; requires approval')

args = parser.parse_args()


def ranges(points):
    runs = []
    for point in sorted(points):
        if runs and runs[-1][1] + 1 == point:
            runs[-1][1] = point
        else:
            runs.append([point, point])
    return ','.join(f'U+{a:04X}' + (f'-{b:04X}' if a != b else '') for a, b in runs)


def inventory(path):
    f = TTFont(path)
    cff_hint_fields = []
    if 'CFF ' in f:
        private = f['CFF '].cff.topDictIndex[0].Private
        cff_hint_fields = [key for key in private.rawDict if key in ('BlueValues', 'OtherBlues', 'FamilyBlues', 'FamilyOtherBlues', 'BlueScale', 'BlueShift', 'BlueFuzz', 'StdHW', 'StdVW', 'StemSnapH', 'StemSnapV')]
    return {
        'cffPrivateHintFields': cff_hint_fields,
        'bytes': path.stat().st_size,
        'sha256': hashlib.sha256(path.read_bytes()).hexdigest(),
        'glyphs': len(f.getGlyphOrder()), 'characters': len(f.getBestCmap()),
        'unicodeRange': ranges(f.getBestCmap()),
        'axes': [{k: getattr(a, k) for k in ('axisTag', 'minValue', 'defaultValue', 'maxValue')} for a in f['fvar'].axes] if 'fvar' in f else [],
        'features': {t: sorted({r.FeatureTag for r in f[t].table.FeatureList.FeatureRecord}) for t in ('GSUB', 'GPOS') if t in f and f[t].table.FeatureList},
        'hintTables': [t for t in ('fpgm', 'prep', 'cvt ', 'gasp') if t in f],
        'hintedGlyphs': sum(bool(getattr(f['glyf'][n], 'program', None) and f['glyf'][n].program.getBytecode()) for n in f.getGlyphOrder()) if 'glyf' in f else 0,
    }


# Conservative scan includes inline JSX strings, entities and all Markdown, not
# just CSS or currently visible metadata. Intersect with the original cmap: never
# steal CJK (or missing Latin characters) from the existing system fallback.
inputs = sorted(p for directory in ('app', 'data', 'content/posts') for p in (ROOT / directory).rglob('*') if p.suffix in ('.tsx', '.ts', '.md', '.css'))
text = ''.join(html.unescape(p.read_text()) for p in inputs)
used = {ord(c) for c in text}
keep = used | set(range(0x20, 0x180)) | {0x2010}
core = set(range(0x20, 0x7F)) | {0x2013, 0x2014, 0x2018, 0x2019, 0x201A, 0x201C, 0x201D, 0x201E, 0x2026}
DEST.mkdir(exist_ok=True)
stage = tempfile.TemporaryDirectory(prefix='mamuso-fonts-')
staging = Path(stage.name)
css = ['/* Generated by scripts/subset-fonts.py. Do not edit. */']
report = {'hinting': (not args.drop_hinting), 'sources': {}, 'outputs': {}, 'usedCharacters': ranges(used), 'missingRequestedCharacters': {}}
preloads = []
for weight, style in ((400, 'Regular'), (700, 'Bold')):
    source = SOURCE / f'CourierPrime-{style}.ttf'
    report['sources'][source.name] = inventory(source)
    cmap = set(TTFont(source).getBestCmap())
    report['missingRequestedCharacters'][style] = ranges(keep - cmap)
    retained = keep & cmap
    actual_parts = []
    for part, points in (('core', retained & core), ('extended', retained - core)):
        font = TTFont(source, recalcTimestamp=False)
        options = subset.Options()
        options.hinting = (not args.drop_hinting)
        # No opt-in GSUB features are used. locl only contains CAT/MOL/ROM
        # substitutions; document language is en. No GPOS/kern/tnum exists.
        options.layout_features = []
        options.recalc_timestamp = False
        options.name_IDs = [0, 1, 2, 3, 4, 5, 6, 13, 14]
        subsetter = subset.Subsetter(options=options)
        subsetter.populate(unicodes=points)
        subsetter.subset(font)
        # fontTools may retain additional cmap aliases for retained glyphs.
        # Remove aliases outside this part before serializing exact CSS ranges.
        for table in font['cmap'].tables:
            if table.isUnicode():
                table.cmap = {u: g for u, g in table.cmap.items() if u in points}
        # Rename even though this OFL has no Reserved Font Name declaration.
        for record in font['name'].names:
            if record.nameID in (1, 3, 4, 6):
                value = {1: 'Mamuso Mono', 3: f'MamusoMono-{style}-{part}', 4: f'Mamuso Mono {style}', 6: f'MamusoMono-{style}'}[record.nameID]
                record.string = value.encode(record.getEncoding())
        font.flavor = 'woff2'
        temp = staging / 'subset.tmp'
        font.save(temp)
        digest = hashlib.sha256(temp.read_bytes()).hexdigest()[:12]
        name = f'mamuso-mono-{style.lower()}-{part}-{digest}.woff2'
        target = staging / name
        temp.replace(target)
        # Reopen actual WOFF2: ranges must reflect encoded cmap, not requests.
        check = TTFont(target)
        actual = set(check.getBestCmap())
        assert actual == points, (name, actual ^ points)
        original = TTFont(source)
        original_glyphs, subset_glyphs = original.getGlyphSet(), check.getGlyphSet()
        for codepoint, glyph in check.getBestCmap().items():
            original_name = original.getBestCmap()[codepoint]
            a = DecomposingRecordingPen(original_glyphs)
            b = DecomposingRecordingPen(subset_glyphs)
            original_glyphs[original_name].draw(a)
            subset_glyphs[glyph].draw(b)
            assert a.value == b.value, (name, codepoint, 'outline changed')
            assert original['hmtx'][original_name] == check['hmtx'][glyph]
        for table, fields in {'head': ('unitsPerEm',), 'hhea': ('ascent', 'descent', 'lineGap'), 'OS/2': ('sTypoAscender', 'sTypoDescender', 'sTypoLineGap', 'usWinAscent', 'usWinDescent')}.items():
            for field in fields:
                assert getattr(original[table], field) == getattr(check[table], field)

        if args.drop_hinting:
            assert not any(t in check for t in ('fpgm', 'prep', 'cvt '))
        else:
            for tag in ('fpgm', 'prep', 'cvt '):
                assert original.getTableData(tag) == check.getTableData(tag)
            for u, glyph in check.getBestCmap().items():
                before = getattr(original['glyf'][original.getBestCmap()[u]], 'program', None)
                after = getattr(check['glyf'][glyph], 'program', None)
                assert (before.getBytecode() if before else b'') == (after.getBytecode() if after else b'')
        assert not report['sources'][source.name]['axes']
        actual_parts.append(actual)
        report['outputs'][name] = inventory(target)
        css.append(f"@font-face {{\n  font-family: 'Mamuso Mono';\n  src: url('/fonts/{name}') format('woff2');\n  font-weight: {weight};\n  font-style: normal;\n  font-display: swap;\n  unicode-range: {ranges(actual)};\n}}")
        if part == 'core':
            preloads.append('/fonts/' + name)
    assert not actual_parts[0] & actual_parts[1]
    assert actual_parts[0] | actual_parts[1] == retained
# Preserve next/font's original adjusted Arial fallback, AFTER the unified real
# family in the stack. Both core and extended share that first family.
original = TTFont(SOURCE / 'CourierPrime-Regular.ttf')
average_text = 'aaabcdeeeefghiijklmnnoopqrrssttuvwxyz      '
average_width = sum(original['hmtx'][original.getBestCmap()[ord(c)]][0] for c in average_text) / len(average_text)
units = original['head'].unitsPerEm
# Match Next 16.3.8's Arial fallback calculation, without processing fonts at build time.
size_adjust = average_width / units / (934.5116279069767 / 2048)
css.append(f"""@font-face {{
  font-family: 'Mamuso Mono Fallback';
  src: local('Arial');
  ascent-override: {abs(original['hhea'].ascent / units / size_adjust * 100):.2f}%;
  descent-override: {abs(original['hhea'].descent / units / size_adjust * 100):.2f}%;
  line-gap-override: {abs(original['hhea'].lineGap / units / size_adjust * 100):.2f}%;
  size-adjust: {size_adjust * 100:.2f}%;
}}
""")
# Publish only after all four files have passed validation.
for name in report['outputs']:
    (DEST / name).write_bytes((staging / name).read_bytes())
(SOURCE / 'subsets.css').write_text('\n\n'.join(css) + '\n')
(SOURCE / 'preloads.ts').write_text('// Generated by scripts/subset-fonts.py.\nexport const photoFontPreloads = ' + ('[\n' + ''.join(f"  '{href}',\n" for href in preloads) + ']') + ' as const\n')
(DEST / 'OFL.txt').write_bytes((SOURCE / 'OFL.txt').read_bytes())
report['serverOnly'] = {'SF-Pro-Display-Medium-latin.otf': inventory(ROOT / 'app/fonts/sf/SF-Pro-Display-Medium-latin.otf')}
(ROOT / 'docs/fonts/inventory.json').write_text(json.dumps(report, indent=2) + '\n')
for stale in DEST.glob('mamuso-mono-*.woff2'):
    if stale.name not in report['outputs']:
        stale.unlink()
stage.cleanup()
print(json.dumps({k: v['bytes'] for k, v in report['outputs'].items()}, indent=2))
